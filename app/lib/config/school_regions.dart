  /// True when [country] has a canonical region list for dropdown UI.
  /// US and CA share one directory group but keep separate region lists.
  static bool hasRegions(String country) =>
      country == 'US' || country == 'CA' || country == 'GB';

  /// Dropdown entries for [country] as (server value, display label).
  /// Empty when the country has no canonical list: those forms keep a
  /// free-text region field instead of guessing values.
  static List<({String value, String label})> forCountry(String country) {
    switch (country) {
      case 'US':
        return [
          for (final s in usStates) (value: s.server, label: s.label),
        ];
      case 'CA':
        return [
          for (final p in caProvinces) (value: p.server, label: p.label),
        ];
      case 'GB':
        return [for (final r in gbRegions) (value: r, label: r)];
      default:
        return const [];
    }
  }
